#!/usr/bin/env node

import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const project_root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const import_root = resolve(project_root, "data/jianpu-imported");
const batch_manifest_path = resolve(import_root, "batch-manifest.json");
const public_root = resolve(project_root, "public/materials/jianpu-imported");
const output_path = resolve(project_root, "src/features/repertoire/importedJianpuData.ts");

const placeholder_titles = new Set([
  "虫虫钢琴-钢琴曲-钢琴谱-Free Piano Sheet Music Download",
  "虫虫钢琴-钢琴曲-钢琴谱－Free Piano Sheet Music Download",
]);

const structured_rights_note =
  "该条目已进入授权教学版，当前已根据原始 CCMZ 数据整理为整首结构化教学谱；原谱页图保留用于来源对照。";

if (!existsSync(batch_manifest_path)) {
  throw new Error(`未找到批处理清单：${batch_manifest_path}`);
}

const batch_manifest = JSON.parse(readFileSync(batch_manifest_path, "utf8"));
const results = Array.isArray(batch_manifest.results) ? batch_manifest.results : [];

rmSync(public_root, { recursive: true, force: true });
mkdirSync(public_root, { recursive: true });

const seen_titles = new Set();
const imported_entries = [];

for (const result of results) {
  if (result?.error || !Array.isArray(result?.pages) || result.pages.length === 0) {
    continue;
  }

  const source_title = normalize_whitespace(String(result.title ?? ""));
  if (!source_title || placeholder_titles.has(source_title)) {
    continue;
  }

  const parsed = parse_source_title(source_title);
  const dedupe_key = parsed.title.toLowerCase();
  if (seen_titles.has(dedupe_key)) {
    continue;
  }

  const pages = copy_pages(result);
  if (pages.length === 0) {
    continue;
  }

  seen_titles.add(dedupe_key);

  imported_entries.push({
    id: `imported-${String(imported_entries.length + 1).padStart(2, "0")}`,
    title: format_display_title(parsed.title),
    attribution: parsed.attribution ?? "原站标题未标注作者",
    source_title,
    source_url: String(result.source_url ?? ""),
    directory: String(result.directory ?? ""),
    page_count: pages.length,
    preview_image: {
      url: pages[0].url,
      alt: `${format_display_title(parsed.title)} 导入简谱第一页预览`,
      width: pages[0].width,
      height: pages[0].height,
    },
    pages,
    rights_note: structured_rights_note,
  });
}

writeFileSync(output_path, build_output(imported_entries), "utf8");

console.log(
  `已同步 ${imported_entries.length} 首导入曲谱到 public/materials/jianpu-imported，并生成 ${output_path}`,
);

function copy_pages(result) {
  const directory = String(result.directory ?? "");
  if (!directory) {
    return [];
  }

  const source_dir = resolve(import_root, directory);
  const destination_dir = resolve(public_root, directory);
  mkdirSync(destination_dir, { recursive: true });

  const pages = [];
  for (const [index, page] of result.pages.entries()) {
    const file = String(page.file ?? "");
    if (!file) {
      continue;
    }

    const source_path = resolve(source_dir, file);
    if (!existsSync(source_path)) {
      continue;
    }

    copyFileSync(source_path, resolve(destination_dir, file));
    pages.push({
      index: index + 1,
      file,
      url: make_public_url(directory, file),
      width: get_dimension(page.width, 483),
      height: get_dimension(page.height, 680),
    });
  }

  return pages;
}

function parse_source_title(raw_title) {
  const without_site = raw_title.replace(/\s*[-－]虫虫钢琴$/u, "").trim();
  const match = without_site.match(
    /^(?<title>.+?)钢琴简谱\s*数字双手(?:\s+(?<attribution>.+))?$/u,
  );

  if (!match?.groups) {
    return {
      title: cleanup_title(without_site),
      attribution: undefined,
    };
  }

  return {
    title: cleanup_title(match.groups.title),
    attribution: cleanup_attribution(match.groups.attribution),
  };
}

function cleanup_title(value) {
  return normalize_whitespace(String(value ?? "").replaceAll("_", " "));
}

function cleanup_attribution(value) {
  const cleaned = normalize_whitespace(String(value ?? "").replaceAll("/", " / "));
  return cleaned || undefined;
}

function normalize_whitespace(value) {
  return value.replace(/\s+/gu, " ").trim();
}

function format_display_title(title) {
  if (title.startsWith("《") && title.endsWith("》")) {
    return title;
  }
  return `《${title}》`;
}

function make_public_url(directory, file) {
  return `/materials/jianpu-imported/${encodeURIComponent(directory)}/${encodeURIComponent(file)}`;
}

function get_dimension(value, fallback) {
  const dimension = Number(value);
  return Number.isFinite(dimension) && dimension > 0 ? dimension : fallback;
}

function build_output(entries) {
  return `/* This file is generated by scripts/sync-imported-jianpu.mjs. */

export interface imported_jianpu_page {
  index: number;
  file: string;
  url: string;
  width: number;
  height: number;
}

export interface imported_jianpu_preview_image {
  url: string;
  alt: string;
  width: number;
  height: number;
}

export interface imported_jianpu_entry {
  id: string;
  title: string;
  attribution: string;
  source_title: string;
  source_url: string;
  directory: string;
  page_count: number;
  preview_image: imported_jianpu_preview_image;
  pages: imported_jianpu_page[];
  rights_note: string;
}

export const imported_jianpu_entries: imported_jianpu_entry[] = ${JSON.stringify(entries, null, 2)};
`;
}
